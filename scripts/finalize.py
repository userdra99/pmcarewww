#!/usr/bin/env python3
"""Post-crawl steps for the static mirror.

1. Saves the site's themed 404 page as /404.html, plus /robots.txt and the RSS feeds
   (/feed.xml, /bm/feed.xml - served for ?feed=rss2[&lang=bm]).
2. Writes legacy-URL routing so existing links (/?page_id=N, /?p=N&lang=bm, /?cat=N&paged=K,
   with any extra params such as fbclid/utm_*) keep resolving:
     - <out>/.htaccess                 (Apache / LiteSpeed)
     - config/nginx-pmcare.conf        (nginx server block)

Usage: python3 -I scripts/finalize.py --out site --data mirror-data --config config
"""
import argparse
import importlib.util
import os
import urllib.error
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("mirror", os.path.join(HERE, "mirror.py"))
mirror = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mirror)

HTACCESS = r"""# PMCare static mirror - Apache / LiteSpeed routing (generated by scripts/finalize.py)
# Serves legacy WordPress query URLs from the mirrored static files without redirecting,
# so existing links, bookmarks and search results keep working unchanged.
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
RewriteEngine On
RewriteBase /

# RSS feeds (?feed=rss2, ?feed=rss2&lang=bm)
RewriteCond %{QUERY_STRING} (?:^|&)feed=[^&]*(?:&|$)
RewriteCond %{QUERY_STRING} (?:^|&)lang=bm(?:&|$)
RewriteRule ^(?:index\.php)?$ /bm/feed.xml [L,T=application/rss+xml]
RewriteCond %{QUERY_STRING} (?:^|&)feed=[^&]*(?:&|$)
RewriteRule ^(?:index\.php)?$ /feed.xml [L,T=application/rss+xml]

RewriteCond %{QUERY_STRING} (?:^|&)lang=bm(?:&|$)
RewriteRule ^(?:index\.php)?$ - [E=PMC_R:/bm]
RewriteCond %{QUERY_STRING} (?:^|&)cat=(\d+)(?:&|$)
RewriteRule ^(?:index\.php)?$ - [E=PMC_R:/category/%1]
RewriteCond %{QUERY_STRING} (?:^|&)p=(\d+)(?:&|$)
RewriteRule ^(?:index\.php)?$ - [E=PMC_R:/post/%1]
RewriteCond %{QUERY_STRING} (?:^|&)page_id=(\d+)(?:&|$)
RewriteRule ^(?:index\.php)?$ - [E=PMC_R:/page/%1]
RewriteCond %{QUERY_STRING} (?:^|&)paged=([2-9]|\d{2,})(?:&|$)
RewriteRule ^(?:index\.php)?$ - [E=PMC_PG:/paged/%1]

RewriteCond %{QUERY_STRING} .
RewriteCond %{ENV:PMC_R}%{ENV:PMC_PG} ^(/.+)$
RewriteRule ^(?:index\.php)?$ %1/index.html [L]

# /index.php with no recognised query -> homepage
RewriteRule ^index\.php$ /index.html [L]
</IfModule>

<IfModule mod_headers.c>
<FilesMatch "\.(?:css|js|woff2?|ttf|eot|otf|svg|png|jpe?g|gif|webp|ico)$">
Header set Cache-Control "public, max-age=2592000"
</FilesMatch>
</IfModule>
"""

NGINX = r"""# PMCare static mirror - nginx server block (generated by scripts/finalize.py)
# Point `root` at the mirrored site directory. Legacy WordPress query URLs are served
# from the static files without a redirect; unknown parameters (fbclid, utm_*) are ignored.
server {
    listen 80;
    server_name www.pmcare.com.my pmcare.com.my;
    root /var/www/pmcare-site;   # <- the mirrored `site/` directory
    index index.html;
    error_page 404 /404.html;

    location = /feed.xml    { default_type application/rss+xml; }
    location = /bm/feed.xml { default_type application/rss+xml; }

    location ~ ^/(?:index\.php)?$ {
        set $pmc_feed "$arg_feed:$arg_lang";
        if ($pmc_feed ~ "^.+:bm$")     { rewrite ^ /bm/feed.xml? last; }
        if ($arg_feed)                 { rewrite ^ /feed.xml? last; }
        set $pmc_r "";
        if ($arg_lang = "bm")          { set $pmc_r /bm; }
        if ($arg_cat ~ "^\d+$")        { set $pmc_r /category/$arg_cat; }
        if ($arg_p ~ "^\d+$")          { set $pmc_r /post/$arg_p; }
        if ($arg_page_id ~ "^\d+$")    { set $pmc_r /page/$arg_page_id; }
        set $pmc_pg "";
        if ($arg_paged ~ "^(?:[2-9]|\d{2,})$") { set $pmc_pg /paged/$arg_paged; }
        rewrite ^ $pmc_r$pmc_pg/index.html? last;
    }

    location / {
        try_files $uri $uri/index.html =404;
    }

    location ~* \.(?:css|js|woff2?|ttf|eot|otf|svg|png|jpe?g|gif|webp|ico)$ {
        try_files $uri =404;
        expires 30d;
        add_header Cache-Control "public";
    }

    # Dynamic WordPress endpoints do not exist in the static mirror.
    location ~ ^/(?:wp-admin|wp-json|xmlrpc\.php|wp-login\.php) { return 404; }
}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="site")
    ap.add_argument("--data", default="mirror-data")
    ap.add_argument("--config", default="config")
    a = ap.parse_args()

    m = mirror.Mirror(a.out, a.data, 1)
    req = urllib.request.Request(mirror.ORIGIN + "/?page_id=999999999",
                                 headers={"User-Agent": mirror.UA, "Accept-Encoding": "identity"})
    try:
        body = urllib.request.urlopen(req, timeout=90).read()
    except urllib.error.HTTPError as e:
        body = e.read()
    text = m.rewrite_html(body.decode("utf-8", "replace"), "/404.html")
    text = text.replace("/page/999999999/#", "/#")  # form anchors would point at the probe URL
    with open(os.path.join(a.out, "404.html"), "w", encoding="utf-8") as f:
        f.write(text)
    missing = [p for p in m.assets if not os.path.exists(mirror.local_file(a.out, p))]
    for p in missing:
        m.queued_assets.add(p)
    m.drain("queued_assets", m.do_asset, "404 assets")

    for src, dest in (("/robots.txt", "robots.txt"), ("/?feed=rss2", "feed.xml"), ("/?feed=rss2&lang=bm", "bm/feed.xml")):
        req = urllib.request.Request(mirror.ORIGIN + src, headers={"User-Agent": mirror.UA, "Accept-Encoding": "identity"})
        body = urllib.request.urlopen(req, timeout=90).read()   # kept verbatim: feeds need absolute URLs
        os.makedirs(os.path.dirname(os.path.join(a.out, dest)), exist_ok=True)
        with open(os.path.join(a.out, dest), "wb") as f:
            f.write(body)

    with open(os.path.join(a.out, ".htaccess"), "w") as f:
        f.write(HTACCESS)
    os.makedirs(a.config, exist_ok=True)
    with open(os.path.join(a.config, "nginx-pmcare.conf"), "w") as f:
        f.write(NGINX)
    print(f"404.html written ({len(missing)} new assets); .htaccess and {a.config}/nginx-pmcare.conf written")


if __name__ == "__main__":
    main()
